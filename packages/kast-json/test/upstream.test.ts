/** Count nodes of one kind across the whole term, iteratively. */
function countNodes(term: KTerm, node: KTerm["node"]): number {
  let count = 0;
  const stack: KTerm[] = [term];
  for (;;) {
    const t = stack.pop();
    if (t === undefined) return count;
    if (t.node === node) count++;
    for (const child of children(t)) stack.push(child);
  }
}

describe("k-distribution term documents (kast --input json test inputs)", () => {
  test("json-in1: parametric #Equals over two Int tokens", () => {
    const result = parseTermDocument(read("k-dist-json-in1.term.json"));
    if (!result.ok) throw new Error(result.problem.message);
    const term = result.term;
    if (term.node !== "KApply") throw new Error(`expected KApply, got ${term.node}`);
    expect(term.label).toBe("#Equals");
    // The KLabel carries sort parameters — a shape the panopticon fixtures
    // never produce, coming straight from K's own test suite.
    expect(term.params).toEqual(["K", "K"]);
    expect(term.args.map((a) => token(a))).toEqual(["3", "4"]);
    expect(countNodes(term, "KOther")).toBe(0);
  });

  test("json-in2 and json-in3 decode with nothing degraded", () => {
    for (const name of ["k-dist-json-in2.term.json", "k-dist-json-in3.term.json"]) {
      const result = parseTermDocument(read(name));
      if (!result.ok) throw new Error(`${name}: ${result.problem.message}`);
      expect(countNodes(result.term, "KOther")).toBe(0);
    }
  });

  test("json-in3 carries KVariables", () => {
    const result = parseTermDocument(read("k-dist-json-in3.term.json"));
    if (!result.ok) throw new Error(result.problem.message);
    expect(countNodes(result.term, "KVariable")).toBe(2);
  });
});

describe("k-distribution outer-parsed definition (kompile --outer-parsed-json input)", () => {
  const result = parseDefinitionDocument(read("k-dist-imp.outer-parsed.json"));

  test("parses strictly", () => {
    if (!result.ok) {
      throw new Error(
        `${result.problem.message}\n` +
          ("issues" in result.problem ? JSON.stringify(result.problem.issues.slice(0, 5), null, 2) : ""),
      );
    }
    expect(result.definition.mainModule).toBe("IMP");
    expect(modulesOf(result.definition)).toHaveLength(89);
  });

  test("covers KBubble — the sentence kompiled output never contains", () => {
    if (!result.ok) throw new Error("parse failed");
    const sentences = modulesOf(result.definition).flatMap((m) => m.localSentences);
    const census = new Map<string, number>();
    for (const s of sentences) census.set(s.node, (census.get(s.node) ?? 0) + 1);
    // Pinned to the byte-exact fixture; a schema regression that silently
    // dropped or misread a sentence kind would move these numbers.
    expect(census.get("KBubble")).toBe(218);
    expect(census.get("KProduction")).toBe(485);
    expect(census.get("KSyntaxAssociativity")).toBe(64);
    expect(census.get("KSyntaxSort")).toBe(21);
    expect(census.get("KSyntaxPriority")).toBe(14);
  });
});

describe("pyk-produced documents (the other writer of KAST v3)", () => {
  test("kinner: a real KEVM configuration decodes with nothing degraded", () => {
    // pyk's own checked-in test data, stored bare — no envelope — which is
    // why this goes through decodeTerm directly.
    const term = decodeTerm(JSON.parse(read("pyk-kinner.bare-term.json")));
    expect(head(term)).toBe("<generatedTop>");
    expect(find(term, "<kevm>")).toBeDefined();
    // Every one of the 147 KApplys carries pyk's `"variable": false`; all of
    // them must read as ordinary KApplys, none as KOther.
    expect(countNodes(term, "KApply")).toBe(147);
    expect(countNodes(term, "KOther")).toBe(0);
  });

  test("KAs decodes from pyk emission", () => {
    const result = parseTermDocument(read("pyk-term-kas.json"));
    if (!result.ok) throw new Error(result.problem.message);
    const seq = result.term;
    if (seq.node !== "KSequence") throw new Error(`expected KSequence, got ${seq.node}`);
    const [as, apply] = seq.items;
    if (as?.node !== "KAs") throw new Error(`expected KAs, got ${as?.node}`);
    if (as.pattern.node !== "KApply") throw new Error("expected KApply pattern");
    expect(as.pattern.label).toBe("foo");
    expect(as.pattern.params).toEqual(["Int"]);
    expect(as.alias).toEqual({ node: "KVariable", name: "P", sort: undefined });
    expect(apply?.node).toBe("KApply");
    expect(findAll(seq, "bar")).toHaveLength(1);
  });

  test("KFlatModuleList with KClaim and KSortSynonym — the --emit-json-spec shape", () => {
    const envelope = openEnvelopeText(read("pyk-spec-kflatmodulelist.json"));
    if (!envelope.ok) throw new Error(envelope.problem.message);
    const parsed = KFlatModuleListSchema.safeParse(envelope.term);
    if (!parsed.success) throw new Error(JSON.stringify(parsed.error.issues.slice(0, 5), null, 2));
    expect(parsed.data.mainModule).toBe("SPEC");
    // KFlatModuleList's modules arrive under the key `term` — an upstream
    // quirk of ToJson.java and pyk both, pinned here.
    const spec = parsed.data.term[0];
    if (spec === undefined) throw new Error("no module");
    expect(spec.localSentences.map((s) => s.node)).toEqual(["KClaim", "KSortSynonym"]);
    const claim = spec.localSentences[0];
    if (claim?.node !== "KClaim") throw new Error("expected KClaim");
    expect(head(claim.body)).toBe("run");
  });
});

/** Deep-copy with every `{node: "KSort", ...}` replaced by its v3 spelling. */
function flattenSorts(value: unknown): unknown {
  if (Array.isArray(value)) return value.map((v) => flattenSorts(v));
  if (!isRecord(value)) return value;
  if (value["node"] === "KSort" && typeof value["name"] === "string") {
    // oxlint-disable-next-line typescript/no-unsafe-type-assertion
    return { node: "KSort", name: flattenSort(value as unknown as SortShape) };
  }
  return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, flattenSorts(v)]));
}

/** JSON re-serialised with sorted keys, so key order cannot mask or fake a diff. */
function canonicalJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map((v) => canonicalJson(v)).join(",")}]`;
  if (!isRecord(value)) return JSON.stringify(value) ?? "null";
  const entries = Object.entries(value)
    .toSorted(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([k, v]) => `${JSON.stringify(k)}:${canonicalJson(v)}`);
  return `{${entries.join(",")}}`;
}

describe("v4 counterparts of the same upstream documents (K at v7.1.337)", () => {
  // K checks in BOTH revisions of the same test files, which makes the whole
  // format change testable as one property: a v4 document with every KSort
  // flattened back to the v3 spelling must be *structurally identical* to its
  // v3 counterpart — same keys, same values, everywhere.

  const PAIRS = [
    "k-dist-json-in1.term.json",
    "k-dist-json-in2.term.json",
    "k-dist-json-in3.term.json",
    "k-dist-imp.outer-parsed.json",
    "pyk-term-kas.json",
    "pyk-spec-kflatmodulelist.json",
    "pyk-term-nested-sorts.json",
  ] as const;

  test("flattening every KSort of a v4 document reproduces its v3 counterpart exactly", () => {
    for (const name of PAIRS) {
      const v3: unknown = JSON.parse(read(name));
      const v4: unknown = JSON.parse(read(join("v4", name)));
      if (!isRecord(v3) || !isRecord(v4)) throw new Error(`${name}: fixture is not an object`);
      expect(v4["version"]).toBe(4);
      expect(v3["version"]).toBe(3);
      expect(canonicalJson(flattenSorts(v4["term"]))).toBe(canonicalJson(v3["term"]));
    }
  });

  test("both versions of a term document decode to the identical KTerm", () => {
    for (const name of ["k-dist-json-in1.term.json", "k-dist-json-in2.term.json", "k-dist-json-in3.term.json"]) {
      const v3 = parseTermDocument(read(name));
      const v4 = parseTermDocument(read(join("v4", name)));
      if (!v3.ok || !v4.ok) throw new Error(`${name}: both versions must parse`);
      expect(v3.version).toBe(3);
      expect(v4.version).toBe(4);
      expect(v4.term).toEqual(v3.term);
      // Stored canonical keys must not churn across the version break.
      expect(canonicalKey(v4.term)).toBe(canonicalKey(v3.term));
    }
  });

  test("json-in1 v4: structured #Equals params arrive flattened, nothing degraded", () => {
    const result = parseTermDocument(read(join("v4", "k-dist-json-in1.term.json")));
    if (!result.ok) throw new Error(result.problem.message);
    const term = result.term;
    if (term.node !== "KApply") throw new Error(`expected KApply, got ${term.node}`);
    expect(term.label).toBe("#Equals");
    expect(term.params).toEqual(["K", "K"]);
    expect(countNodes(term, "KOther")).toBe(0);
  });

  test("the v4 outer-parsed definition parses strictly with the same census as v3", () => {
    const result = parseDefinitionDocument(read(join("v4", "k-dist-imp.outer-parsed.json")));
    if (!result.ok) {
      throw new Error(
        `${result.problem.message}\n` +
          ("issues" in result.problem ? JSON.stringify(result.problem.issues.slice(0, 5), null, 2) : ""),
      );
    }
    expect(result.version).toBe(4);
    expect(result.definition.mainModule).toBe("IMP");
    expect(modulesOf(result.definition)).toHaveLength(89);
    const sentences = modulesOf(result.definition).flatMap((m) => m.localSentences);
    const census = new Map<string, number>();
    for (const s of sentences) census.set(s.node, (census.get(s.node) ?? 0) + 1);
    expect(census.get("KBubble")).toBe(218);
    expect(census.get("KProduction")).toBe(485);
  });

  test("the v4 definition carries real structured parametric sorts", () => {
    // MInt{Width} ×81 in this document — the exact shape the format change
    // exists for.
    const result = parseDefinitionDocument(read(join("v4", "k-dist-imp.outer-parsed.json")));
    if (!result.ok) throw new Error("parse failed");
    let structured = 0;
    for (const m of modulesOf(result.definition)) {
      for (const s of m.localSentences) {
        if (s.node === "KProduction" && s.sort.params.length > 0) {
          structured++;
          expect(flattenSort(s.sort)).toBe(`${s.sort.name}{${s.sort.params.map((p) => p.name).join(",")}}`);
        }
      }
    }
    expect(structured).toBeGreaterThan(0);
  });

  test("v4 pyk emission reads identically to v3 pyk emission", () => {
    const v3 = parseTermDocument(read("pyk-term-kas.json"));
    const v4 = parseTermDocument(read(join("v4", "pyk-term-kas.json")));
    if (!v3.ok || !v4.ok) throw new Error("both must parse");
    expect(v4.term).toEqual(v3.term);

    const envelope = openEnvelopeText(read(join("v4", "pyk-spec-kflatmodulelist.json")));
    if (!envelope.ok) throw new Error(envelope.problem.message);
    expect(envelope.version).toBe(4);
    const parsed = KFlatModuleListSchema.safeParse(envelope.term);
    if (!parsed.success) throw new Error(JSON.stringify(parsed.error.issues.slice(0, 5), null, 2));
    expect(parsed.data.term[0]?.localSentences.map((s) => s.node)).toEqual(["KClaim", "KSortSynonym"]);
  });
});

describe("sorts nested two levels deep, from pyk at both versions", () => {
  // The only fixture in this package whose sorts nest deeper than one level,
  // and the only producer that could make one: K's Java frontend refuses a
  // user-defined parametric sort outright ("User-defined parametric sorts are
  // currently unsupported", k-distribution/tests/regression-new/checks/
  // checkParametricSort.k), so the deepest sort it emits is an instantiated
  // MInt{64} — which fixtures/{term,definition}/**/mint-width* cover. pyk has
  // no such restriction, and writes Outer{Inner{Int},Int} at both versions.
  const NAME = "pyk-term-nested-sorts.json";
  const FLAT = "Outer{Inner{Int},Int}";
  const STRUCTURE = {
    name: "Outer",
    params: [
      { name: "Inner", params: [{ name: "Int", params: [] }] },
      { name: "Int", params: [] },
    ],
  };

  const v3 = parseTermDocument(read(NAME));
  const v4 = parseTermDocument(read(join("v4", NAME)));

  test("both versions decode to the identical KTerm, with equal canonical keys", () => {
    if (!v3.ok || !v4.ok) throw new Error("both versions must parse");
    expect(v3.version).toBe(3);
    expect(v4.version).toBe(4);
    expect(v4.term).toEqual(v3.term);
    expect(canonicalKey(v4.term)).toBe(canonicalKey(v3.term));
  });

  test("the depth-2 sort arrives flat on the token, the variable and the label", () => {
    if (!v4.ok) throw new Error("must parse");
    const seq = v4.term;
    if (seq.node !== "KSequence") throw new Error(`expected KSequence, got ${seq.node}`);
    const [tok, variable, applied] = seq.items;
    if (tok?.node !== "KToken") throw new Error("expected KToken");
    expect(tok.sort).toBe(FLAT);
    if (variable?.node !== "KVariable") throw new Error("expected KVariable");
    expect(variable.sort).toBe(FLAT);
    if (applied?.node !== "KApply") throw new Error("expected KApply");
    expect(applied.params).toEqual([FLAT, "Inner{Int}"]);
  });

  test("unflattenSort takes the depth-2 spelling back apart", () => {
    if (!v3.ok) throw new Error("must parse");
    const tok = v3.term.node === "KSequence" ? v3.term.items[0] : undefined;
    if (tok?.node !== "KToken") throw new Error("expected KToken");
    expect(unflattenSort(tok.sort)).toEqual(STRUCTURE);
    // And the v4 bytes carry that same structure literally, not as a string.
    expect(read(join("v4", NAME))).not.toContain(FLAT);
    expect(read(NAME)).toContain(FLAT);
  });
});

describe("pyk's KSyntaxLexical spelling bug", () => {
  // pyk emits `"node": "KSyntaxLexcial"` — letters transposed — at
  // `pyk/src/pyk/kast/outer.py:464` (v7.1.191; still present at v7.1.337).
  // K's Java JsonParser expects `KSyntaxLexical` (JsonParser.java:74), and
  // pyk's own `from_dict` dispatch does too, so pyk cannot round-trip the
  // node it writes.  This package follows the Java authority: the correct
  // spelling parses, the typo does not, and this test is where that divergence
  // is recorded so nobody mistakes the rejection for a transcription error.
  const lexical = { name: "Digit", regex: "[0-9]", att: { node: "KAtt", att: {} } };

  test("the Java spelling parses", () => {
    expect(SentenceSchema.safeParse({ node: "KSyntaxLexical", ...lexical }).success).toBe(true);
  });

  test("pyk's misspelling is rejected, deliberately", () => {
    expect(SentenceSchema.safeParse({ node: "KSyntaxLexcial", ...lexical }).success).toBe(false);
  });
});
