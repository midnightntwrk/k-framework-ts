/**
 * Conformance against K's *own* test material, at tag `v7.1.191`.
 *
 * The fixtures under `fixtures/upstream/` are not made by this package's
 * authors' toolchain runs; they come from the K repository's checked-in test
 * data and from pyk's own serializer.  See `fixtures/PROVENANCE.md` for the
 * exact `git show` commands and the generator script.
 *
 * Two families:
 *
 * - `k-dist-*` — checked in by the K project itself under
 *   `k-distribution/tests/regression-new/`, consumed there by `kast --input
 *   json` and `kompile --outer-parsed-json`.  These are documents K's Java
 *   frontend demonstrably accepts, so a reader that fails on them is wrong.
 *   `k-dist-imp.outer-parsed.json` is the only fixture anywhere in this
 *   package containing `KBubble` (218 of them): an *outer-parsed* definition
 *   still carries its rule bodies as unparsed bubbles, which `kompile
 *   --emit-json` output never does.
 *
 * - `pyk-*` — produced by pyk `v7.1.191`'s `to_dict()`, the other writer of
 *   KAST v3.  `pyk-kinner.bare-term.json` is pyk's own checked-in test data (a
 *   real KEVM configuration, `"variable"` key and all); the other three were
 *   generated by `fixtures/upstream/generate-pyk-fixtures.py` specifically to
 *   cover `KAs`, `KClaim`, `KSortSynonym`, `KFlatModuleList` and sorts nested
 *   two levels deep, none of which any K-produced fixture in this package
 *   contains — the last of them because K's Java frontend cannot produce it at
 *   all (see the nested-sorts test below).
 */

