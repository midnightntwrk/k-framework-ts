/** How many hex characters pyk's `all_rules` key keeps (`ktool/kprint.py:235`). */
export const RULE_HASH_PREFIX_LENGTH = 12;

/**
 * Parse `allRules.txt` — `<UNIQUE_ID> <file>:<line>:<col>` per line,
 * `\n`-joined with no trailing newline (`Kompile.java:378-380`).
 *
 * The separator is a **space**, not a tab, and it is the *first* one: a path
 * containing spaces keeps them.  Blank lines are skipped, as pyk skips them
 * (`ktool/kprint.py:231-233`).  A line whose location does not end in
 * `:<digits>:<digits>` still yields an entry — `location` is the whole
 * remainder — with `line`/`column` set to `NaN`, because losing the rule
 * entirely would be worse than losing its position.
 */
export function parseAllRules(text: string): ParsedAllRules {
  const allRulesRows: RuleLocation[] = [];
  const allRules = new Map<string, RuleLocation>();
  const allRulesByPrefix = new Map<string, RuleLocation>();
  const rowsById = new Map<string, RuleLocation[]>();
  const distinctLines = new Set<string>();
  for (const rawLine of text.split("\n")) {
    const line = rawLine.trim();
    if (line === "") continue;
    distinctLines.add(line);
    const space = line.indexOf(" ");
    // `str.partition(' ')` with no separator gives `(line, '', '')` — pyk
    // records the whole line as a hash with an empty location.
    const uniqueId = space === -1 ? line : line.slice(0, space);
    const location = space === -1 ? "" : line.slice(space + 1);
    const entry = Object.freeze({ uniqueId, location, ...splitLocation(location) });
    allRulesRows.push(entry);
    allRules.set(uniqueId, entry);
    allRulesByPrefix.set(uniqueId.slice(0, RULE_HASH_PREFIX_LENGTH), entry);
    const rows = rowsById.get(uniqueId);
    if (rows === undefined) rowsById.set(uniqueId, [entry]);
    else rows.push(entry);
  }
  const duplicates = [...rowsById]
    .filter(([, rows]) => rows.length > 1)
    .map(([ruleId, locations]) => Object.freeze({ ruleId, locations: Object.freeze([...locations]) }));
  return Object.freeze({
    allRulesRows: Object.freeze(allRulesRows),
    allRules,
    allRulesByPrefix,
    duplicateRuleIds: Object.freeze(duplicates),
    distinctLineCount: distinctLines.size,
  });
}

/** Complete duplicate-id audit, preserving source order and identical repeated rows. */
export function duplicateRuleIds(text: string): readonly DuplicateRuleId[] {
  return parseAllRules(text).duplicateRuleIds;
}

/** pyk's `all_rules` set size: distinct non-blank stripped lines. */
export function distinctLineCount(text: string): number {
  return parseAllRules(text).distinctLineCount;
}

/**
 * `<file>:<line>:<col>` split from the right.
 *
 * Splitting from the left would break every path in real output: K writes
 * absolute paths, and `/nix/store/…/domains.md:1409:31` has no colon before the
 * ones that matter but `C:\k\domains.md:12:3` does.
 *
 * A field that is not a decimal integer — including an **empty** one — makes
 * the whole location unparsed: `location` keeps everything and `line`/`column`
 * are `NaN`.  The empty case has to be tested explicitly because `Number("")`
 * is `0`, so `a::` would otherwise report line 0, column 0 as though those were
 * real positions; K's `Location` is 1-based and never writes an empty field.
 */
function splitLocation(location: string): { readonly source: string; readonly line: number; readonly column: number } {
  const unparsed = { source: location, line: Number.NaN, column: Number.NaN };
  const lastColon = location.lastIndexOf(":");
  if (lastColon === -1) return unparsed;
  const prevColon = location.lastIndexOf(":", lastColon - 1);
  if (prevColon === -1) return unparsed;
  const lineText = location.slice(prevColon + 1, lastColon);
  const columnText = location.slice(lastColon + 1);
  if (lineText === "" || columnText === "") return unparsed;
  const line = Number(lineText);
  const column = Number(columnText);
  if (!Number.isInteger(line) || !Number.isInteger(column)) return unparsed;
  return { source: location.slice(0, prevColon), line, column };
}

/**
 * Look a rule up by its `UNIQUE_ID` or by any prefix of it at least
 * {@link RULE_HASH_PREFIX_LENGTH} characters long.
 *
 * The full hash is tried first, then the 12-character index — so both the
 * spelling `kcovr.py` uses and the one `ktool/kprint.py` uses resolve — an
 * ambiguity this package settles rather than inherits.
 * A prefix shorter than 12 characters is not looked up at all:
 * it would need a linear scan and would be ambiguous by construction.
 */
export function lookupRule(layout: KompiledLayout, hash: string): RuleLocation | undefined {
  const exact = layout.allRules.get(hash);
  if (exact !== undefined) return exact;
  if (hash.length < RULE_HASH_PREFIX_LENGTH) return undefined;
  const byPrefix = layout.allRulesByPrefix.get(hash.slice(0, RULE_HASH_PREFIX_LENGTH));
  // A 12-char hit must still be consistent with the longer key that was asked
  // for, or this would answer a question it was not asked.
  return byPrefix !== undefined && byPrefix.uniqueId.startsWith(hash) ? byPrefix : undefined;
}

