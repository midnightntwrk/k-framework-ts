/**
 * Recompute what `configVars.sh` would say, from `compiled.json` — a
 * transcription of `CompiledDefinition.initializeConfigurationVariableDefaultSorts`
 * (`CompiledDefinition.java:82-139`).
 *
 * Two independent uses.  It is the **fallback** when a directory has no
 * `configVars.sh` (older K, or a directory assembled by hand).  And it is an
 * **oracle**: running it against a directory that *does* have the file checks a
 * KAST-level reading of the definition against what the Java frontend wrote,
 * which is the strongest cross-artifact check available without `konvert`.
 *
 * The algorithm, verbatim from Java: visit every rule body of the main module
 * looking for `project:<Sort>(Map:lookup(_, #token("$X", KConfigVar)))`; the
 * variable is `X` (the `$` dropped) and its sort is `<Sort>` — except that a
 * projection to `K` is *written out* as `KItem` (`:104-105`), which is the one
 * place the file disagrees with the map Java keeps in memory.
 *
 * # "the main module" means its import closure
 *
 * `:86` reads `kompiledDefinition.mainModule().rules()`, and a Scala `Module`'s
 * `sentences` is `localSentences | importedSentences` (`outer.scala:174`), with
 * `rules` and `productions` collected from `sentences` (`:312`, `:188`).  So the
 * Java pass sees every rule and production of every module the main module
 * transitively imports, not just the ones written in it — and it has to, since
 * a `configuration` declared in `IMP-SYNTAX` and imported into `IMP` would
 * otherwise contribute nothing.  `KDefinition.rules` and
 * `KDefinition.productions` (`kast/src/outer.ts`) are that same closure, walked
 * breadth-first from the main module, which is why they are what this reads.
 *
 * Two deliberate deviations, both forced:
 *
 * - **Order.** Java streams a Scala `Set` of rules (`:86`), so the order it
 *   writes lines in is unspecified.  Ours is definition order.  Compare these
 *   as sets, never as lists.
 * - **Duplicates.** Java appends a line per *occurrence*, so a variable read by
 *   two rules would appear twice in the file.  We key by name, first occurrence
 *   winning the position and — matching Java's `HashMap.put` — the last winning
 *   the sort.
 */
export function deriveConfigVars(definition: KDefinition): ConfigVars {
  const configVars: string[] = [];
  const configVarSorts = new Map<string, string>();

  // `Module.rules()` in the Java frontend collects `Rule` only — `Claim` is a
  // sibling of `Rule` under `RuleOrClaim` and is collected separately
  // (`outer.scala:312`, `:349`) — so this visits rules and not claims, matching
  // `:86`.  `KDefinition.rules` is `modules.flatMap(moduleRules)` over the main
  // module's import closure, which is what `mainModule().rules()` returns.
  for (const rule of definition.rules) {
    collect((term) => {
      const found = configVarProjection(term);
      if (found === undefined) return;
      if (!configVarSorts.has(found.name)) configVars.push(found.name);
      configVarSorts.set(found.name, found.sort);
    }, rule.body);
  }

  return Object.freeze({
    configVars,
    configVarSorts,
    configVarModules: deriveConfigVarModules(definition),
  });
}

/**
 * `project:<Sort>(Map:lookup(_, #token("$X", KConfigVar)))` → `{name, sort}`.
 *
 * The label spellings are `KLabels.MAP_LOOKUP` (`Map:lookup`) and the
 * `project:` prefix the frontend generates; `Sorts.KConfigVar()` is the token's
 * sort.  Everything else in the tree is ignored.
 */
function configVarProjection(term: KInner): { readonly name: string; readonly sort: string } | undefined {
  if (term.node !== "KApply") return undefined;
  if (!term.label.name.startsWith("project:") || term.args.length !== 1) return undefined;
  const lookup = term.args[0];
  if (lookup?.node !== "KApply" || lookup.label.name !== "Map:lookup" || lookup.args.length !== 2) return undefined;
  const token = lookup.args[1];
  if (token?.node !== "KToken" || token.sort.name !== "KConfigVar") return undefined;
  if (!token.token.startsWith("$")) return undefined;

  const projected = term.label.name.slice("project:".length);
  // `CompiledDefinition.java:104-105`: the *file* says KItem where the
  // projection says K.  The in-memory map keeps K; only the written line is
  // rewritten, and this function reproduces the written line.
  return { name: token.token.slice(1), sort: projected === "K" ? "KItem" : projected };
}

/** The `parser` attribute's key.  Not in `Atts`, so it is looked up by name. */
const PARSER_ATT = "parser";

/**
 * `declaredConfigVarModule_*` — from the main module's productions (its import
 * closure, as above) carrying both `cell` and `parser`
 * (`CompiledDefinition.java:127-138`).
 *
 * `parser` is a *two-dimensional* attribute: `;` separates entries and `,`
 * separates the two fields of each (`StringUtil.splitTwoDimensionalAtt`,
 * `:589-597`).  Java raises `KEMException` on an entry that is not a pair; we
 * skip it, because a reader refusing to open a directory over a malformed
 * attribute in a production it does not care about is the wrong trade.
 *
 * The one subtlety is that Java's `String.split(",")` **drops trailing empty
 * fields** and JavaScript's does not, so `parser("PGM,TEST-SYNTAX,")` is a
 * well-formed pair to Java and a 3-element array here — silently skipped by a
 * bare `length !== 2`.  The trailing empties are therefore dropped before the
 * length check.  Each `;`-entry is trimmed *before* its `,`-split for the same
 * reason: `splitOneDimensionalAtt` does `att.trim().split(",")` (`:581-587`),
 * so trailing whitespace after a trailing comma is gone by the time Java's
 * split runs and cannot save the empty field from being dropped.
 *
 * IMP has no `cell`+`parser` production, so this path is covered by a synthetic
 * definition in `test/layout.test.ts` rather than by the fixture.
 */
function deriveConfigVarModules(definition: KDefinition): ReadonlyMap<string, string> {
  const modules = new Map<string, string>();
  for (const production of definition.productions) {
    if (!production.att.has(Atts.CELL)) continue;
    const parser = attByName(production.att, PARSER_ATT);
    if (parser === undefined) continue;
    for (const entry of parser.trim().split(";")) {
      const fields = entry.trim().split(",");
      while (fields.length > 0 && fields[fields.length - 1] === "") fields.pop();
      if (fields.length !== 2) continue;
      const [name, module] = fields.map((part) => part.trim());
      if (name !== undefined && module !== undefined && name !== "") modules.set(name, module);
    }
  }
  return modules;
}

/**
 * An attribute's value by raw name, as a string.
 *
 * `KAtt.get` is keyed by an `AttKey`, and `parser` has no registered key in
 * `packages/kast`'s `Atts` — an unregistered name decodes to an `ANY_TYPE` key,
 * so it is reachable by iterating entries.  Non-string values (there should be
 * none for `parser`) read as `undefined`.
 */
function attByName(
  att: Iterable<{ readonly key: { readonly name: string }; readonly value: unknown }>,
  name: string,
): string | undefined {
  for (const entry of att) {
    if (entry.key.name === name) return typeof entry.value === "string" ? entry.value : undefined;
  }
  return undefined;
}
