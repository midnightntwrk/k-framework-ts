/**
 * The already-read bytes {@link parseKompiledLayout} needs.
 *
 * The four required fields are the artifacts `kompile` always writes; the two
 * optional ones default to empty, which is what a
 * directory with no configuration variables and no locatable rules would say
 * anyway.  Absence of a *required* file is the caller's error to raise — this
 * function never sees a filesystem, so it cannot tell "absent" from "not read".
 */
export interface KompiledLayoutInput {
  readonly mainModule: string;
  readonly mainSyntaxModule: string;
  readonly backend: string;
  /** `timestamp`'s mtime in milliseconds.  Never its content. */
  readonly timestampMtimeMs: number;
  /** `timestamp`'s mtime in nanoseconds, if the reader has it. */
  readonly timestampMtimeNs?: bigint;
  /**
   * `configVars.sh`'s text, if the file exists.
   *
   * `undefined` and `""` are **not** the same input: the former sets
   * {@link KompiledLayout.hasConfigVarsFile} to `false` and permits the
   * `compiled.json` fallback, the latter records a present-but-empty file and
   * forbids it.  A reader that cannot distinguish "absent" from "empty" should
   * pass `undefined`.
   */
  readonly configVarsSh?: string;
  /** `allRules.txt`'s text, if the file exists. */
  readonly allRulesTxt?: string;
}

/** Assemble a {@link KompiledLayout} from bytes.  Pure; frozen result. */
export function parseKompiledLayout(input: KompiledLayoutInput): KompiledLayout {
  const { allRules, allRulesByPrefix } = parseAllRules(input.allRulesTxt ?? "");
  const configVars = parseConfigVars(input.configVarsSh ?? "");
  return Object.freeze({
    mainModule: input.mainModule.trim(),
    mainSyntaxModule: input.mainSyntaxModule.trim(),
    backend: input.backend.trim(),
    timestampMtimeMs: input.timestampMtimeMs,
    timestampMtimeNs: input.timestampMtimeNs,
    allRules,
    allRulesByPrefix,
    hasConfigVarsFile: input.configVarsSh !== undefined,
    configVars: configVars.configVars,
    configVarSorts: configVars.configVarSorts,
    configVarModules: configVars.configVarModules,
  });
}

