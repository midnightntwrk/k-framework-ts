/**
 * The cheap half of a `*-kompiled/` directory: the marker files, `allRules.txt`
 * and `configVars.sh`, parsed from strings that somebody else read.
 *
 * **Nothing in this file touches the filesystem.**  That is deliberate and it
 * is the reason the module exists separately from `fs.ts`: the whole of the
 * layout contract — including its three traps — is decidable from bytes, so it
 * is testable without a directory, works under a virtual filesystem, and can be
 * fed by a build system that already has the bytes in hand.
 *
 * # The three traps, encoded
 *
 * 1. **`timestamp` contains no timestamp.**  It is seven bytes —
 *    `AC ED 00 05 74 00 00`, a Java-serialized empty string
 *    (`KompileFrontEnd.java:116` writes `""`).  Its *mtime* is the contract, so
 *    {@link KompiledLayoutInput} takes an `mtimeMs` number and there is no code
 *    path anywhere in this package that reads the file's content.  It is also
 *    written **last**, so it post-dates every other artifact in the directory.
 * 2. **The markers have no trailing newline.**  `KompileFrontEnd.java:98-110`
 *    writes bare names, and pyk reads them **unstripped**
 *    (`ktool/kompile.py:655,660`) — which only works because of that.  We trim
 *    anyway: a `mainModule.txt` that someone's editor added a newline to should
 *    not produce a module name that matches nothing.
 * 3. **`configVars.sh` is a shell script and must never be run.**  It is
 *    generated by string concatenation (`CompiledDefinition.java:81-139`) in
 *    three fixed forms, and a regex reads all three.  Executing a file out of a
 *    build directory to learn three variable names is not a trade worth making.
 *
 * # `allRules.txt` is not a list of all rules
 *
 * `Kompile.java:363-381` emits a line only for a sentence that (a) is in the
 * **main module**, (b) is a `RuleOrClaim`, and (c) carries *all* of `Source`,
 * `Location` and `UNIQUE_ID`.  Prelude rules that reached the main module do
 * appear; rules of imported modules that did not, and any rule the frontend
 * synthesised without a source location, do not.  Treat it as a
 * `UNIQUE_ID → source location` index, which is what it is, and join it with
 * `KDefinition.sentenceByUniqueId` when you want the sentence itself.
 */

import { Atts, collect, type KDefinition, type KInner } from "@kframework-ts/kast";

