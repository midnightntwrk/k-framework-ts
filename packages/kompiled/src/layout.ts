/**
 * The value of `backend.txt`.
 *
 * The four names are `KompileBackend` (`ktool/kompile.py:205-209`), and pyk
 * *throws* on anything else because it constructs an `Enum`.  We do not: the
 * union is open (`string & {}`), so an unknown backend reads back as itself and
 * the caller decides.  Refusing to load a directory because K grew a fifth
 * backend would be the wrong failure.
 */
export type KompileBackend = "llvm" | "haskell" | "kore" | "maude" | (string & {});

/** One line of `allRules.txt`, split. */
export interface RuleLocation {
  /**
   * The rule's `UNIQUE_ID` attribute — a full-length lowercase sha256 hex
   * string as `Kompile.java:378` writes it.
   *
   * This is the join key into `KDefinition.sentenceByUniqueId`.
   */
  readonly uniqueId: string;
  /** `<file>:<line>:<col>` exactly as written — what pyk's `all_rules` maps to. */
  readonly location: string;
  /**
   * The file part.  Split from the **right**, so colons inside a path survive:
   * upstream's own output is full of `/nix/store/…` paths, and a Windows
   * `C:\…` path would otherwise lose its drive letter.
   */
  readonly source: string;
  /** `Location.startLine` (`Kompile.java:373`). */
  readonly line: number;
  /** `Location.startColumn` (`Kompile.java:374`). */
  readonly column: number;
}

/** Every occurrence of one `UNIQUE_ID` in an `allRules.txt`, including identical repeated rows. */
export interface DuplicateRuleId {
  /** The duplicated `UNIQUE_ID`. */
  readonly ruleId: string;
  /** The source-order rows that claim it. */
  readonly locations: readonly RuleLocation[];
}

/** The one row parse from which the compatibility maps and integrity facts are derived. */
export interface ParsedAllRules {
  /** Every non-blank row in source order; unlike the maps, this never deduplicates. */
  readonly allRulesRows: readonly RuleLocation[];
  /** Full-id compatibility index; repeated ids keep their last row. */
  readonly allRules: ReadonlyMap<string, RuleLocation>;
  /** Twelve-character-prefix compatibility index; repeated prefixes keep their last row. */
  readonly allRulesByPrefix: ReadonlyMap<string, RuleLocation>;
  /** Every id that occurs on multiple rows, including byte-identical repeated rows. */
  readonly duplicateRuleIds: readonly DuplicateRuleId[];
  /** pyk's `all_rules` set size: distinct non-blank stripped lines. */
  readonly distinctLineCount: number;
}

/** What `configVars.sh` declares (`CompiledDefinition.java:81-139`). */
export interface ConfigVars {
  /**
   * The `declaredConfigVars=( … )` array, in file order, **without** the `$`.
   *
   * K writes `t.s().substring(1)`, i.e. `PGM` for the configuration variable
   * `$PGM`, and this keeps that spelling.
   */
  readonly configVars: readonly string[];
  /** `declaredConfigVar_<NAME>='<Sort>'` — the variable's default sort. */
  readonly configVarSorts: ReadonlyMap<string, string>;
  /** `declaredConfigVarModule_<name>='<Module>'` — from `cell`+`parser` productions. */
  readonly configVarModules: ReadonlyMap<string, string>;
}

/**
 * Everything a kompiled directory says about itself before any term algebra is
 * involved — pyk's `DefinitionInfo` (`ktool/kompile.py:643-668`) plus the two
 * side files it does not model.
 *
 * Cheap enough to load eagerly, and everything expensive
 * ({@link KompiledDefinition}'s artifacts) is not here.
 */
export interface KompiledLayout extends ConfigVars {
  /** `mainModule.txt`, trimmed — `DefinitionInfo.main_module_name` (`:660-661`). */
  readonly mainModule: string;
  /** `mainSyntaxModule.txt`, trimmed — `DefinitionInfo.syntax_module_name` (`:663-664`). */
  readonly mainSyntaxModule: string;
  /** `backend.txt`, trimmed — `DefinitionInfo.backend` (`:655-657`). */
  readonly backend: KompileBackend;
  /**
   * `timestamp`'s modification time, in **milliseconds**.
   *
   * pyk exposes nanoseconds (`st_mtime_ns`, `:667-668`); JavaScript's `Date`
   * and `fs.Stats.mtimeMs` are milliseconds, and a `number` cannot hold
   * nanosecond precision past 2^53 anyway.  {@link timestampMtimeNs} is beside
   * it for anyone who needs pyk's exact number.
   */
  readonly timestampMtimeMs: number;
  /** The same instant in nanoseconds, as pyk reports it.  `undefined` if the reader did not supply it. */
  readonly timestampMtimeNs: bigint | undefined;
  /**
   * `allRules.txt`, keyed by the **full** `UNIQUE_ID`.
   *
   * pyk truncates to 12 characters (`ktool/kprint.py:235`) but uses the full
   * hash in `kcovr.py:178-195` and `coverage.py:63-75`; keying by the full hash
   * loses nothing, and {@link allRulesByPrefix} is the pyk-compatible view.
   */
  readonly allRules: ReadonlyMap<string, RuleLocation>;
  /**
   * The same map keyed by the first 12 hex characters — pyk's
   * `KPrint.all_rules` (`ktool/kprint.py:222-236`), whose values are the
   * `location` strings.
   *
   * A collision keeps the **last** line, matching Python's `dict` assignment.
   * At 12 hex characters a collision needs ~16 million rules to be likely, and
   * upstream has never hit one.
   */
  readonly allRulesByPrefix: ReadonlyMap<string, RuleLocation>;
  /**
   * Whether `configVars.sh` **existed**, as opposed to whether it said anything.
   *
   * The three {@link ConfigVars} fields cannot answer that question: a
   * definition with no configuration variables and no `cell`+`parser`
   * production produces a `configVars.sh` that parses to three empty
   * collections, and that is indistinguishable from no file at all.  The
   * difference matters, because it decides whether `KompiledDefinition`'s
   * `configVars` getter may fall back to re-deriving them from `compiled.json`
   * — a fallback that *throws* on a directory built without `--emit-json`,
   * which is the CLI default.  So the presence of the file is recorded here
   * rather than guessed at from its contents.
   */
  readonly hasConfigVarsFile: boolean;
}

