// `declaredConfigVar_PGM='Pgm'` — `CompiledDefinition.java:110-116`.
const CONFIG_VAR_SORT = /^declaredConfigVar_([A-Za-z0-9_]+)='([^']*)'/gmu;
// `declaredConfigVarModule_name='MODULE'` — `CompiledDefinition.java:135`.
const CONFIG_VAR_MODULE = /^declaredConfigVarModule_([A-Za-z0-9_]+)='([^']*)'/gmu;
// The `declaredConfigVars=(\n    'PGM'\n)` array — `:87,117-118,127`.
const CONFIG_VARS_ARRAY = /^declaredConfigVars=\(([\s\S]*?)^\)/mu;
const QUOTED = /'([^']*)'/gu;

/**
 * Read `configVars.sh` by regex — never by executing it.
 *
 * The file is built by string concatenation in `CompiledDefinition.java`, in
 * exactly three forms, and the generator quotes nothing: a sort or module name
 * containing a `'` would produce a shell script this regex mis-reads *and* that
 * bash mis-reads, so there is no fidelity lost relative to running it.  K sort
 * and module names cannot contain quotes.
 *
 * A missing or truncated file yields empty results rather than an error —
 * `configVars.sh` is re-derivable from `compiled.json` ({@link deriveConfigVars}),
 * so its absence is recoverable and should not stop a load.
 *
 * Note the `declaredConfigVarModule_` prefix is a *superstring* of
 * `declaredConfigVar_`: the sort regex would match `declaredConfigVarModule_X`
 * as the variable `Module_X` if it were not anchored on the `=`, which it is
 * (`[A-Za-z0-9_]+` is greedy and stops at `=`, so `Module_X='M'` parses as name
 * `Module_X`).  The module lines are therefore removed before the sort pass.
 */
export function parseConfigVars(text: string): ConfigVars {
  const configVarModules = new Map<string, string>();
  for (const match of text.matchAll(CONFIG_VAR_MODULE)) {
    const [, name, module] = match;
    if (name !== undefined && module !== undefined) configVarModules.set(name, module);
  }

  // Delete the module lines so the sort pattern cannot see them.  The pattern
  // does not match the line's terminating `\n`, so the newline survives the
  // replacement and every surviving line still starts at a real line start —
  // which is what keeps the `^` anchors of the sort pass honest.  (A pattern
  // that swallowed the newline would splice two lines together and let the
  // sort pass match mid-line.)
  const withoutModules = text.replace(CONFIG_VAR_MODULE, "");
  const configVarSorts = new Map<string, string>();
  for (const match of withoutModules.matchAll(CONFIG_VAR_SORT)) {
    const [, name, sort] = match;
    if (name !== undefined && sort !== undefined) configVarSorts.set(name, sort);
  }

  const configVars: string[] = [];
  const array = CONFIG_VARS_ARRAY.exec(text);
  if (array?.[1] !== undefined) {
    for (const quoted of array[1].matchAll(QUOTED)) {
      const [, name] = quoted;
      if (name !== undefined) configVars.push(name);
    }
  }

  return Object.freeze({ configVars, configVarSorts, configVarModules });
}

