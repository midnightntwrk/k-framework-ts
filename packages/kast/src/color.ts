/** A K color name, as spelled in `color.py`'s enum *values*. */
export type Color = (typeof COLORS)[number];

const COLOR_SET: ReadonlySet<string> = new Set<string>(COLORS);

/** Byte-for-byte membership in {@link COLORS} (`Color(text)`, `color.py:11`). */
export function isColor(text: string): text is Color {
  return COLOR_SET.has(text);
}

/**
 * `Color(text)` — the enum's value lookup, which raises `ValueError` on a miss
 * (`att.py:224,232` rely on it to reject a bad `color(...)` attribute).
 */
export function parseColor(text: string): Color {
  if (!isColor(text)) throw new TypeError(`Not a valid color: ${JSON.stringify(text)}`);
  return text;
}
