/**
 * Memo table for {@link hashOf}.  A `WeakMap` because terms are the keys and
 * nothing here should keep one alive; frozen plain objects are perfectly good
 * weak keys.
 */
const HASHES = new WeakMap<KInner, string>();

/**
 * pyk's `KAst.hash` (`kast.py:32-35` with `utils.py:373-376`): the sha256 hex
 * digest of the UTF-8 bytes of `json.dumps(to_dict(), sort_keys=True)`.
 *
 * The digest is the identity pyk uses for a term — KCFG node ids are these
 * strings — so it is also the right key for a term-keyed `Map` or `Set` here.
 *
 * The canonical JSON is pure ASCII by construction, so "UTF-8 bytes" and
 * "ASCII bytes" are the same bytes; `hash_str` encodes UTF-8 either way.
 */
export function hashOf(term: KInner): string {
  const cached = HASHES.get(term);
  if (cached !== undefined) return cached;
  const digest = hashOfDict(toDict(term));
  HASHES.set(term, digest);
  return digest;
}

/**
 * {@link hashOf} for anything that already knows how to `toDict` itself —
 * `KAst.hash` (`kast.py:32-35`) is declared on the whole `KAst` hierarchy, not
 * just on `KInner`, and `ktool/kprint.py:238-240` reaches for
 * `definition.hash`.
 *
 * `KDefinition.hash` is the getter that wants this; a `KSentence` or a
 * `KFlatModule` hashes as `hashOfDict(sentenceToDict(s))` /
 * `hashOfDict(flatModuleToDict(m))`.  Unmemoised — the argument is a freshly
 * built dict, so there is nothing stable to key a memo table on.
 */
export function hashOfDict(value: JsonValue): string {
  return createHash("sha256").update(canonicalJson(value), "utf8").digest("hex");
}
