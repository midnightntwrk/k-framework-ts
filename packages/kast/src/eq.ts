// Equality         //
//////////////////////

/** Structural equality of two sorts, including their parameters. */
export function eqSort(a: KSort, b: KSort): boolean {
  if (a === b) return true;
  const stack: (readonly [KSort, KSort])[] = [[a, b]];
  for (;;) {
    const pair = stack.pop();
    if (pair === undefined) return true;
    const [l, r] = pair;
    if (l === r) continue;
    if (l.name !== r.name || l.params.length !== r.params.length) return false;
    for (let i = l.params.length - 1; i >= 0; i--) stack.push([at(l.params, i), at(r.params, i)]);
  }
}

/** Structural equality of two labels, including their sort parameters. */
export function eqLabel(a: KLabel, b: KLabel): boolean {
  if (a === b) return true;
  if (a.name !== b.name || a.params.length !== b.params.length) return false;
  for (let i = 0; i < a.params.length; i++) {
    if (!eqSort(at(a.params, i), at(b.params, i))) return false;
  }
  return true;
}

/**
 * Structural equality of two terms — the frozen-dataclass `==` pyk gets for
 * free.
 *
 * Everything is compared: a `KToken`'s sort, a `KVariable`'s sort, a
 * `KApply`'s label *parameters*.  That last one is worth reading twice,
 * because `match` deliberately ignores label parameters (`inner.py:429`) while
 * equality does not — two terms that match each other need not be equal.
 */
export function eq(a: KInner, b: KInner): boolean {
  if (a === b) return true;
  const stack: (readonly [KInner, KInner])[] = [[a, b]];
  for (;;) {
    const pair = stack.pop();
    if (pair === undefined) return true;
    const [l, r] = pair;
    if (l === r) continue;

    switch (l.node) {
      case "KToken":
        if (r.node !== "KToken" || l.token !== r.token || !eqSort(l.sort, r.sort)) return false;
        break;
      case "KVariable":
        if (r.node !== "KVariable" || l.name !== r.name) return false;
        if (l.sort === undefined || r.sort === undefined) {
          if (l.sort !== r.sort) return false;
        } else if (!eqSort(l.sort, r.sort)) {
          return false;
        }
        break;
      case "KApply": {
        if (r.node !== "KApply" || l.args.length !== r.args.length || !eqLabel(l.label, r.label)) return false;
        for (let i = l.args.length - 1; i >= 0; i--) stack.push([at(l.args, i), at(r.args, i)]);
        break;
      }
      case "KAs":
        if (r.node !== "KAs") return false;
        stack.push([l.alias, r.alias], [l.pattern, r.pattern]);
        break;
      case "KRewrite":
        if (r.node !== "KRewrite") return false;
        stack.push([l.rhs, r.rhs], [l.lhs, r.lhs]);
        break;
      case "KSequence": {
        if (r.node !== "KSequence" || l.items.length !== r.items.length) return false;
        for (let i = l.items.length - 1; i >= 0; i--) stack.push([at(l.items, i), at(r.items, i)]);
        break;
      }
    }
  }
}

