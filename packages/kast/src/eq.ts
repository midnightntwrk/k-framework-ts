/**
 * Structural equality, pyk's total order, and pyk-compatible term hashes.
 *
 * Python gets all three for free from frozen dataclasses: `==` is structural,
 * `<` is `KAst.__lt__` (`kast.py:37-46`), and `hash` is sha256 over
 * `json.dumps(to_dict(), sort_keys=True)` (`kast.py:32-35`).  TypeScript gets
 * none of them, and downstream pyk code leans on all three constantly —
 * `subst1[v] == subst2[v]`, `term != old_term` fixpoints, `constraint not in
 * constraints`.  So they are written out here, explicitly and without
 * recursion.
 *
 * # Byte parity with `json.dumps` is the point of {@link hashOf}
 *
 * A KCFG node id *is* a term hash.  If our canonical JSON differs from
 * Python's by one byte, every hash differs, and no artifact pyk wrote can be
 * matched against a term we built.  {@link canonicalJson} therefore reproduces
 * `json.dumps(..., sort_keys=True)` exactly: `", "` and `": "` separators
 * (CPython's defaults, *not* the compact ones), keys sorted, and
 * `ensure_ascii=True` escaping — every code point outside `\x20`-`\x7e`
 * emitted as `\uXXXX` in lowercase hex, astral characters as their surrogate
 * pair, `\b \t \n \f \r` in their short forms.  `test/hash-parity.test.ts`
 * pins this against digests generated by pyk itself.
 *
 * # Nothing recurses
 *
 * {@link eq}, {@link compare}, {@link canonicalJson} and therefore
 * {@link hashOf} all run on explicit work stacks.
 */

import { createHash } from "node:crypto";
import type { KInner, KLabel, KSort } from "./inner.js";
import { toDict, type JsonArray, type JsonObject, type JsonValue } from "./json.js";

/** Index into an array whose bounds the caller has already established. */
function at<T>(xs: readonly T[], i: number): T {
  const x = xs[i];
  if (x === undefined) throw new RangeError(`Index ${i} is out of range (length ${xs.length})`);
  return x;
}

