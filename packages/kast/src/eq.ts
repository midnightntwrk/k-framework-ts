/** The named entries of `json.encoder.ESCAPE_DCT` (CPython `json/encoder.py:24-34`). */
const SHORT_ESCAPES: Readonly<Record<string, string>> = {
  "\\": "\\\\",
  '"': '\\"',
  "\b": "\\b",
  "\f": "\\f",
  "\n": "\\n",
  "\r": "\\r",
  "\t": "\\t",
};

/**
 * `json.encoder.py_encode_basestring_ascii` — a JSON string literal in which
 * every character outside `\x20`-`\x7e` is escaped.
 *
 * Iterating by UTF-16 code unit is not an approximation here: CPython emits an
 * astral code point as its surrogate *pair* (`encoder.py:53-60`), which is
 * exactly the pair JavaScript already stores.
 */
function encodeAscii(text: string): string {
  let out = '"';
  for (let i = 0; i < text.length; i++) {
    const ch = text.charAt(i);
    const short = SHORT_ESCAPES[ch];
    if (short !== undefined) {
      out += short;
      continue;
    }
    // Code *units*, not code points: an astral character must come out as its
    // surrogate pair, which is what CPython emits (`encoder.py:53-60`).
    // oxlint-disable-next-line unicorn/prefer-code-point
    const code = text.charCodeAt(i);
    out += code >= 0x20 && code <= 0x7e ? ch : `\\u${code.toString(16).padStart(4, "0")}`;
  }
  return `${out}"`;
}

/** A literal to emit verbatim, or a value still to be encoded. */
type Emit = { readonly lit: string } | { readonly val: JsonValue };

/** `Array.isArray` as a guard that keeps the `readonly`. */
function isJsonArray(value: JsonValue): value is JsonArray {
  return Array.isArray(value);
}

/**
 * `json.dumps(value, sort_keys=True)`, byte for byte.
 *
 * Default separators — `", "` between items and `": "` after a key — which is
 * what `json.dumps` uses when `indent` is `None` and `separators` is not
 * given.  Keys are sorted; every key a KAST dict carries is ASCII, so Python's
 * code-point sort and JavaScript's code-unit sort cannot disagree.
 *
 * Non-integer numbers throw: `repr(float)` and `Number.prototype.toString`
 * agree on far less than they appear to, and no KAST dict contains a float
 * (`arity` is the only number in the format).
 */
export function canonicalJson(value: JsonValue): string {
  const out: string[] = [];
  const stack: Emit[] = [{ val: value }];

  for (;;) {
    const item = stack.pop();
    if (item === undefined) return out.join("");
    if ("lit" in item) {
      out.push(item.lit);
      continue;
    }

    const v = item.val;
    if (v === null) {
      out.push("null");
    } else if (typeof v === "boolean") {
      out.push(v ? "true" : "false");
    } else if (typeof v === "number") {
      if (!Number.isInteger(v)) throw new TypeError(`canonicalJson: not an integer: ${v}`);
      out.push(String(v));
    } else if (typeof v === "string") {
      out.push(encodeAscii(v));
    } else if (isJsonArray(v)) {
      out.push("[");
      stack.push({ lit: "]" });
      for (let i = v.length - 1; i >= 0; i--) {
        stack.push({ val: at(v, i) });
        if (i > 0) stack.push({ lit: ", " });
      }
    } else {
      const obj: JsonObject = v;
      const keys = Object.keys(obj).toSorted();
      out.push("{");
      stack.push({ lit: "}" });
      for (let i = keys.length - 1; i >= 0; i--) {
        const key = at(keys, i);
        stack.push({ val: obj[key] ?? null }, { lit: `${encodeAscii(key)}: ` });
        if (i > 0) stack.push({ lit: ", " });
      }
    }
  }
}

