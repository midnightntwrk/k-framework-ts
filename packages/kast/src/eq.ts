/** `-1` when the left operand sorts first, `1` when the right does, `0` when neither. */
export type Ordering = -1 | 0 | 1;

/**
 * Python's `str` comparison: by **code point**, not by UTF-16 code unit.
 *
 * JavaScript's `<` on strings compares code units, and the two disagree
 * whenever one string has an astral character (stored as a surrogate pair, in
 * U+D800-U+DFFF) where the other has a character in U+E000-U+FFFF.  Rare in a
 * K term, but the whole value of matching pyk's order is that it matches
 * everywhere.
 */
function cmpString(a: string, b: string): Ordering {
  if (a === b) return 0;
  let i = 0;
  let j = 0;
  for (;;) {
    if (i >= a.length) return j >= b.length ? 0 : -1;
    if (j >= b.length) return 1;
    const ca = a.codePointAt(i) ?? 0;
    const cb = b.codePointAt(j) ?? 0;
    if (ca !== cb) return ca < cb ? -1 : 1;
    i += ca > 0xff_ff ? 2 : 1;
    j += cb > 0xff_ff ? 2 : 1;
  }
}

function cmpNumber(a: number, b: number): Ordering {
  if (a === b) return 0;
  return a < b ? -1 : 1;
}

/**
 * One pending comparison.  The stack is processed strictly left to right and
 * the first non-zero answer wins, which is exactly Python's lexicographic
 * tuple comparison.
 */
type CompareTask =
  | { readonly kind: "inner"; readonly a: KInner; readonly b: KInner }
  | { readonly kind: "sort"; readonly a: KSort; readonly b: KSort }
  | { readonly kind: "label"; readonly a: KLabel; readonly b: KLabel }
  | { readonly kind: "text"; readonly a: string; readonly b: string }
  | { readonly kind: "count"; readonly a: number; readonly b: number };

/**
 * pyk's total order on terms — `KAst.__lt__` (`kast.py:37-46`).
 *
 * Two rules, both transcribed literally:
 *
 * 1. **Different node kinds compare by class name.**  `type(self).__name__ <
 *    type(other).__name__`, and since our `node` tags *are* those class names
 *    the comparison is on the tag itself.  The resulting order is
 *    `KApply < KAs < KRewrite < KSequence < KToken < KVariable`.
 * 2. **The same node kind compares its shallow field tuple**, in dataclass
 *    declaration order: `KToken` is `(token, sort)`, `KVariable` is
 *    `(name, sort)`, `KApply` is `(label, args)`, `KAs` is
 *    `(pattern, alias)`, `KRewrite` is `(lhs, rhs)`, `KSequence` is
 *    `(items,)`, and `KSort`/`KLabel` are both `(name, params)`.  Sequences
 *    compare elementwise and then by length, as Python tuples do.
 *
 * On top of that, `KVariable` overrides `__lt__` (`inner.py:310-317`): for the
 * *same name*, an unsorted variable sorts before a sorted one, and the sorts
 * are never compared.  `sort_assoc_label` in `manip.py` consumes this.
 *
 * # The one deviation
 *
 * pyk's override answers `self.sort is None`, so for two variables that are
 * equal *and unsorted* — `KVariable('X') < KVariable('X')` — it returns
 * `True`, in **both** directions.  That is a genuine upstream bug: the
 * relation is not antisymmetric there, and no three-way comparator can
 * reproduce it.  This function answers `0` for that pair, i.e. it treats equal
 * terms as equal.  Everything else, including all six rows of pyk's
 * `test_kast_compare`, is bit-for-bit pyk.
 */
export function compare(a: KInner, b: KInner): Ordering {
  const stack: CompareTask[] = [{ kind: "inner", a, b }];

  /**
   * A Python tuple of sorts: elementwise up to the shorter length, then by
   * length.  The length task is pushed first so it is examined last.
   */
  const pushSorts = (l: readonly KSort[], r: readonly KSort[]): void => {
    stack.push({ kind: "count", a: l.length, b: r.length });
    for (let i = Math.min(l.length, r.length) - 1; i >= 0; i--) {
      stack.push({ kind: "sort", a: at(l, i), b: at(r, i) });
    }
  };

  const pushInners = (l: readonly KInner[], r: readonly KInner[]): void => {
    stack.push({ kind: "count", a: l.length, b: r.length });
    for (let i = Math.min(l.length, r.length) - 1; i >= 0; i--) {
      stack.push({ kind: "inner", a: at(l, i), b: at(r, i) });
    }
  };

  for (;;) {
    const task = stack.pop();
    if (task === undefined) return 0;

    switch (task.kind) {
      case "text": {
        const result = cmpString(task.a, task.b);
        if (result !== 0) return result;
        break;
      }
      case "count": {
        const result = cmpNumber(task.a, task.b);
        if (result !== 0) return result;
        break;
      }
      case "sort":
      case "label": {
        // `(name, params)` for both — `KSort` and `KLabel` declare the same
        // two fields in the same order.
        if (task.a === task.b) break;
        pushSorts(task.a.params, task.b.params);
        stack.push({ kind: "text", a: task.a.name, b: task.b.name });
        break;
      }
      case "inner": {
        const l = task.a;
        const r = task.b;
        if (l === r) break;
        if (l.node !== r.node) return cmpString(l.node, r.node);

        switch (l.node) {
          case "KToken":
            if (r.node !== "KToken") break;
            stack.push({ kind: "sort", a: l.sort, b: r.sort }, { kind: "text", a: l.token, b: r.token });
            break;
          case "KVariable": {
            if (r.node !== "KVariable") break;
            // `inner.py:310-317`: the same name with either side unsorted is
            // decided on sortedness alone, and the sorts are never compared.
            if (l.name === r.name && (l.sort === undefined || r.sort === undefined)) {
              if (l.sort === r.sort) break;
              return l.sort === undefined ? -1 : 1;
            }
            // Past that guard, equal names imply both sorts are present; when
            // the names differ the name task returns before the sort task runs.
            if (l.sort !== undefined && r.sort !== undefined) {
              stack.push({ kind: "sort", a: l.sort, b: r.sort });
            }
            stack.push({ kind: "text", a: l.name, b: r.name });
            break;
          }
          case "KApply":
            if (r.node !== "KApply") break;
            pushInners(l.args, r.args);
            stack.push({ kind: "label", a: l.label, b: r.label });
            break;
          case "KAs":
            if (r.node !== "KAs") break;
            stack.push({ kind: "inner", a: l.alias, b: r.alias }, { kind: "inner", a: l.pattern, b: r.pattern });
            break;
          case "KRewrite":
            if (r.node !== "KRewrite") break;
            stack.push({ kind: "inner", a: l.rhs, b: r.rhs }, { kind: "inner", a: l.lhs, b: r.lhs });
            break;
          case "KSequence":
            if (r.node !== "KSequence") break;
            pushInners(l.items, r.items);
            break;
        }
        break;
      }
    }
  }
}

/** `a < b` under {@link compare} — the spelling `KAst.__lt__` provides. */
export function lt(a: KInner, b: KInner): boolean {
  return compare(a, b) < 0;
}

